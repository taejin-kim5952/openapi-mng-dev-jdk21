package com.kt.openapi.web.cmmn.logutil;

public class LOGSTANDARDSecurity {
	private String type;
	private String event;
	private String target;
	private String multiTarget;
	private String detail;
	private String reason;
	private String exported;
	private String personalInfoList;

	public String getType() {
		return type;
	}

	public void setType(String type) {
		this.type = type;
	}

	public String getEvent() {
		return event;
	}

	public void setEvent(String event) {
		this.event = event;
	}

	public String getTarget() {
		return target;
	}

	public void setTarget(String target) {
		this.target = target;
	}

	public String getMultiTarget() {
		return multiTarget;
	}

	public void setMultiTarget(String multiTarget) {
		this.multiTarget = multiTarget;
	}

	public String getDetail() {
		return detail;
	}

	public void setDetail(String detail) {
		this.detail = detail;
	}

	public String getReason() {
		return reason;
	}

	public void setReason(String reason) {
		this.reason = reason;
	}

	public String getExported() {
		return exported;
	}

	public void setExported(String exported) {
		this.exported = exported;
	}

	public String getPersonalInfoList() {
		return personalInfoList;
	}

	public void setPersonalInfoList(String personalInfoList) {
		this.personalInfoList = personalInfoList;
	}
	
	
}
